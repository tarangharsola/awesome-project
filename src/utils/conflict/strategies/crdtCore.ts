/**
 * Simple sequence‑based CRDT (RGA – Replicated Growable Array) implementation.
 * It provides deterministic conflict‑free handling of concurrent inserts and deletes.
 * Each operation carries a globally unique identifier (clientId + counter) and a
 * reference to the preceding element (prevId). The document is reconstructed by
 * traversing the linked list of visible elements.
 */

type CharId = string; // format: `${clientId}-${counter}`

type Operation =
  | { type: 'insert'; id: CharId; prevId: CharId | null; value: string }
  | { type: 'delete'; id: CharId };

interface Element {
  id: CharId;
  value: string;
  visible: boolean;
  prevId: CharId | null;
  nextId: CharId | null;
}

export class CRDT {
  private elements: Map<CharId, Element> = new Map();
  private headId: CharId | null = null; // sentinel for start of document
  private tailId: CharId | null = null;

  constructor(initialContent = '') {
    // Initialise with a single invisible head element to simplify insert logic
    const head: Element = { id: 'HEAD', value: '', visible: false, prevId: null, nextId: null };
    this.elements.set(head.id, head);
    this.headId = head.id;
    // Insert initial content sequentially
    let prev = head.id;
    for (let i = 0; i < initialContent.length; i++) {
      const charId = `init-${i}`;
      const elem: Element = { id: charId, value: initialContent[i], visible: true, prevId: prev, nextId: null };
      this.elements.set(charId, elem);
      const prevElem = this.elements.get(prev)!;
      prevElem.nextId = charId;
      prev = charId;
    }
    this.tailId = prev;
  }

  /** Apply a local insert generated by the current client */
  public localInsert(prevId: CharId | null, value: string, clientId: string, counter: number): Operation {
    const id = `${clientId}-${counter}`;
    const op: Operation = { type: 'insert', id, prevId, value };
    this.applyOperation(op);
    return op;
  }

  /** Apply a local delete generated by the current client */
  public localDelete(id: CharId): Operation {
    const op: Operation = { type: 'delete', id };
    this.applyOperation(op);
    return op;
  }

  /** Integrate a remote operation (insert or delete) */
  public applyOperation(op: Operation) {
    if (op.type === 'insert') {
      this.integrateInsert(op);
    } else if (op.type === 'delete') {
      this.integrateDelete(op);
    }
  }

  private integrateInsert(op: Extract<Operation, { type: 'insert' }>) {
    if (this.elements.has(op.id)) return; // idempotent
    const newElem: Element = {
      id: op.id,
      value: op.value,
      visible: true,
      prevId: op.prevId,
      nextId: null,
    };
    // Find insertion point
    const prevElem = op.prevId ? this.elements.get(op.prevId) : this.elements.get(this.headId!);
    if (!prevElem) {
      // Fallback to head if predecessor missing (possible out‑of‑order delivery)
      const head = this.elements.get(this.headId!);
      if (head) {
        newElem.prevId = head.id;
        newElem.nextId = head.nextId;
        head.nextId = newElem.id;
      }
    } else {
      // Insert after prevElem, preserving existing next chain
      newElem.nextId = prevElem.nextId;
      prevElem.nextId = newElem.id;
    }
    this.elements.set(newElem.id, newElem);
    // Update tail reference if inserted at the end
    if (!newElem.nextId) this.tailId = newElem.id;
  }

  private integrateDelete(op: Extract<Operation, { type: 'delete' }>) {
    const elem = this.elements.get(op.id);
    if (elem) {
      elem.visible = false;
    }
  }

  /** Reconstruct the current visible document string */
  public getDocument(): string {
    let result = '';
    let currentId = this.elements.get(this.headId!)?.nextId ?? null;
    while (currentId) {
      const elem = this.elements.get(currentId);
      if (!elem) break;
      if (elem.visible) result += elem.value;
      currentId = elem.nextId;
    }
    return result;
  }

  /** Export the full operation log for state transfer (used on sync‑request) */
  public exportState(): Operation[] {
    const ops: Operation[] = [];
    for (const elem of this.elements.values()) {
      if (elem.id === 'HEAD') continue;
      if (elem.visible) {
        ops.push({ type: 'insert', id: elem.id, prevId: elem.prevId, value: elem.value });
      } else {
        ops.push({ type: 'delete', id: elem.id });
      }
    }
    return ops;
  }
}
